#!/usr/bin/env python3
"""Generate Rust builders from the same Schema.org 30.0 JSON-LD as spatie/schema-org."""

import argparse
import json
import re
import subprocess
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = "https://raw.githubusercontent.com/schemaorg/schemaorg/main/data/releases/30.0/schemaorg-all-https.jsonld"
VOCABULARY = ROOT / "generator/schemaorg-all-https.jsonld"
KEYWORDS = set("as async await break const continue crate dyn else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while abstract become box do final gen macro override priv typeof unsized virtual yield try union".split())


def snake(name):
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()
    name = re.sub(r"\W", "_", name)
    if name[0].isdigit():
        name = "_" + name
    return name + "_" if name in KEYWORDS else name


def many(value):
    return value if isinstance(value, list) else [value]


def label(node):
    value = node.get("rdfs:label", "")
    return value.get("@value", "") if isinstance(value, dict) else value


def generate():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", action="store_true", help="Download the pinned upstream definition again")
    args = parser.parse_args()
    if args.refresh or not VOCABULARY.exists():
        with urllib.request.urlopen(SOURCE) as response:
            VOCABULARY.write_bytes(response.read())
    nodes = json.loads(VOCABULARY.read_text())["@graph"]
    classes = sorted((n for n in nodes if "rdfs:Class" in many(n.get("@type", []))
                      and "schema:DataType" not in many(n.get("@type", []))
                      and label(n) not in {"", "DataType", "Float", "Integer", "URL", "Class"}
                      and n["@id"].startswith("schema:")), key=label)
    properties = sorted((n for n in nodes if "rdf:Property" in many(n.get("@type", [])) and label(n)
                         and n["@id"].startswith("schema:")), key=label)
    names = {n["@id"]: "ThreeDimensionalModel" if label(n) == "3DModel" else label(n) for n in classes}
    out = ['// @generated by generator/generate.py; do not edit.', 'use crate::{Entity, Graph, IntoProperty, MultiTypedEntity, SchemaType};',
           '/// Schema.org vocabulary version.', 'pub const SCHEMA_VERSION: &str = "30.0";',
           '/// Every generated Schema.org type name.', 'pub const TYPE_NAMES: &[&str] = &[']
    out += [json.dumps(name) + ',' for name in names.values()]
    out += ['];', '/// Type markers used by the generated builders.', 'pub mod types {']
    for node in classes:
        name = names[node['@id']]
        out += [f'/// Schema.org `{label(node)}`. See <https://schema.org/{label(node)}>.' ,
                '#[derive(Debug, Clone, Copy, PartialEq, Eq)]', f'pub struct {name};',
                f'impl super::SchemaType for {name} {{ const NAME: &\'static str = "{name}"; }}']
    out += ['}']
    for name in names.values():
        out += [f'/// Fluent builder for Schema.org `{name}`.', f'pub type {name} = Entity<types::{name}>;']
    out += ['/// Factory for all Schema.org types.', '#[derive(Debug, Clone, Copy)]', 'pub struct Schema;', 'impl Schema {']
    for name in names.values():
        out += [f'/// Create a `{name}` builder.', f'pub fn {snake(name)}() -> {name} {{ {name}::new() }}']
    out += ['}', 'impl<T> Entity<T> {']
    seen = set()
    for node in properties:
        prop = label(node)
        method = snake(prop)
        if method in seen:
            raise ValueError(f"Property naming collision: {prop}")
        seen.add(method)
        out += [f'/// Set `{prop}`. See <https://schema.org/{prop}>.',
                f'pub fn {method}(&mut self, value: impl IntoProperty) -> &mut Self {{ self.set_property("{prop}", value) }}']
    out += ['}']
    for owner in ['Graph', 'MultiTypedEntity']:
        out += [f'impl {owner} {{']
        for name in names.values():
            ensure = f'self.ensure("{name}", Self::IDENTIFIER_DEFAULT)' if owner == 'Graph' else f'self.graph.ensure("{name}", Graph::IDENTIFIER_DEFAULT)'
            out += [f'/// Get or create a shared handle to the default `{name}` node.', f'pub fn {snake(name)}(&mut self) -> Entity {{ {ensure} }}']
        out += ['}']
    smoke = ['//! Generated vocabulary coverage; regenerate with generator/generate.py.',
             'use spatie_schema_org::*;',
             '#[test]', 'fn every_type_has_a_builder_and_collection_accessor() {',
             'let mut graph = Graph::new();', 'let mut multi = MultiTypedEntity::new();']
    for name in names.values():
        smoke += [f'assert_eq!(Schema::{snake(name)}().get_type(), "{name}");',
                  f'assert_eq!({name}::new().get_type(), "{name}");',
                  f'assert_eq!(graph.{snake(name)}().get_type(), "{name}");',
                  f'assert_eq!(multi.{snake(name)}().get_type(), "{name}");']
    smoke += ['}', '#[test]', 'fn every_property_maps_to_its_schema_name() {', 'let mut entity = Schema::thing();']
    for node in properties:
        prop = label(node)
        smoke += [f'entity.{snake(prop)}("sentinel");', f'assert_eq!(entity.get_property("{prop}"), Some(serde_json::json!("sentinel")));']
    smoke += ['}', '#[test]', 'fn every_enumeration_value_is_a_schema_url() {']
    constants = 0
    for node in nodes:
        for type_id in many(node.get('@type', [])):
            if type_id not in names or not node['@id'].startswith('schema:'):
                continue
            constant = snake(label(node)).upper()
            if not constant:
                continue
            name = names[type_id]
            url = 'https://schema.org/' + node['@id'].split(':', 1)[1]
            out += [f'impl Entity<types::{name}> {{', f'/// Schema.org enumeration value `{label(node)}`.', f'pub const {constant}: &\'static str = "{url}";', '}']
            smoke += [f'assert_eq!({name}::{constant}, "{url}");']
            constants += 1
    smoke += ['}']
    path = ROOT / 'src/generated.rs'
    path.write_text('\n'.join(out) + '\n')
    test_path = ROOT / 'tests/vocabulary.rs'
    test_path.write_text('\n'.join(smoke) + '\n')
    subprocess.run(['rustfmt', '--edition', '2024', str(path), str(test_path)], check=True)
    print(f'Generated {len(classes)} types, {len(properties)} properties, {constants} enumeration values')


if __name__ == '__main__':
    generate()
